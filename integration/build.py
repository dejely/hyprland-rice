#!/usr/bin/env python3
"""Build the pinned shell with reviewable compatibility changes outside vendor/."""
from pathlib import Path
import argparse
import shutil

ROOT = Path(__file__).resolve().parents[1]


def build(destination):
    destination = Path(destination).resolve()
    if destination == ROOT or ROOT in destination.parents:
        raise ValueError('Runtime must be outside the checkout')
    if destination.exists() and any(destination.iterdir()):
        if not (destination / '.rice-generated').exists():
            raise ValueError('Refusing to replace a directory not generated by this integration')
        shutil.rmtree(destination)
    destination.mkdir(parents=True, exist_ok=True)
    (destination / '.rice-generated').touch()
    shutil.copytree(ROOT / 'vendor/end4-pC', destination, dirs_exist_ok=True, symlinks=True)
    for path in destination.rglob('*'):
        if path.is_symlink() or not path.is_file() or path.suffix not in ('.qml', '.sh', '.py', '.json'):
            continue
        text = path.read_text()
        text = text.replace('illogical-impulse', 'hyprland-rice/end4')
        path.write_text(text)

    def replace(name, old, new):
        path = destination / name
        text = path.read_text()
        if old not in text:
            raise ValueError(f'Patch anchor missing: {name}: {old[:70]}')
        path.write_text(text.replace(old, new))

    replace('shell.qml', '        FirstRunExperience.load()', '// First-run wallpaper replacement is managed by the integration.')
    replace('shell.qml', '        ConflictKiller.load()', '// Profile switching manages competing processes.')
    replace('shell.qml', '        LyricsService.restartLyrics()', '// Lyrics are opt-in.')
    replace('panelFamilies/IllogicalImpulseFamily.qml', '    PanelLoader { component: Lock {} }', '    // hyprlock remains the session lock.')
    replace('panelFamilies/IllogicalImpulseFamily.qml', '    PanelLoader { component: Polkit {} }', '    // Keep the existing session polkit agent.')
    replace('modules/common/Directories.qml', '`${Directories.state}/user', '`${Directories.state}/hyprland-rice/end4/user')
    replace('modules/common/Persistent.qml', 'property string fileDir: Directories.state', 'property string fileDir: `${Directories.state}/hyprland-rice/end4`')
    replace('services/Wallpapers.qml', '`${Directories.pictures}/Wallpapers`', '`${Directories.pictures}/wallpapers`')
    replace('modules/common/Appearance.qml', 'property int normal: 17', 'property int normal: 20')
    replace('modules/common/Appearance.qml', 'property int large: 23', 'property int large: 20')
    # Do not apply illogical-impulse Lua overrides to JaKooLit on startup.
    replace('services/MaterialThemeLoader.qml', '        HyprlandConfig.applyBorderColors()', '        // Keep JaKooLit window borders.')
    replace('services/MaterialThemeLoader.qml', '        const json = JSON.parse(fileContent)', '''        let json;
        try { json = JSON.parse(fileContent); } catch (e) { return; }
        if (!json || !json.primary || !json.background) return;
        for (const value of Object.values(json)) {
            if (typeof value !== "string" || !/^#[0-9a-fA-F]{6}$/.test(value)) return;
        }''')
    replace('modules/common/Config.qml', '''property string update: "kitty -1 --hold=yes fish -i -c 'pkexec pacman -Syu'"''', '''property string update: "kitty --hold python3 \\\"" + Quickshell.shellPath("integration/host.py") + "\\\" update"''')
    replace('modules/common/Directories.qml', '`${Directories.scriptPath}/colors/switchwall.sh`', '`${Quickshell.shellPath("integration")}/switchwall.sh`')
    # Remove upstream's implicit shared API key; leave account services unconfigured.
    import re
    weather = destination / 'services/Weather.qml'
    source = weather.read_text()
    source = re.sub(r'const defaultApiKey = "[^"]*"', 'const defaultApiKey = ""', source)
    source = source.replace('    function getData() {', '    function getData() {\n        if (!root.city && !root.gpsActive) return;')
    weather.write_text(source)
    # Integration-owned scripts use system Python, never an unconfigured upstream venv.
    for wrapper in destination.rglob('*-venv.sh'):
        original = wrapper.read_text()
        script = re.search(r'\$SCRIPT_DIR/([^"\s]+\.py)', original)
        if script:
            wrapper.write_text('#!/usr/bin/env bash\nset -euo pipefail\nSCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"\nexec python3 "$SCRIPT_DIR/' + script[1] + '" "$@"\n')
    # Existing Hyprland dispatch syntax (the pinned fork targets Lua Hyprland).
    import re
    for path in destination.rglob('*.qml'):
        text = path.read_text()
        text = re.sub(r'hl\.dsp\.focus\(\{\s*workspace = (\$\{[^}]+\}) \}\)', r'workspace \1', text)
        text = re.sub(r'hl\.dsp\.focus\(\{ window = "address:(\$\{[^}]+\})" \}\)', r'focuswindow address:\1', text)
        text = re.sub(r'hl\.dsp\.window\.close\(\{ window = "address:(\$\{[^}]+\})" \}\)', r'closewindow address:\1', text)
        text = re.sub(r'hl\.dsp\.window\.move\(\{ workspace = (\$\{[^}]+\}), follow = false, window = "address:(\$\{[^}]+\})" \}\)', r'movetoworkspacesilent \1,address:\2', text)
        text = re.sub(r'hl\.dsp\.window\.swap\(\{ window = "address:(\$\{[^}]+\})" \}\)', r'swapwindow address:\1', text)
        text = text.replace('hl.dsp.global("quickshell:wallpaperSelectorToggle")', 'global quickshell:wallpaperSelectorToggle')
        # Isolated smoke runs must never place panels on the physical screen.
        text = text.replace('model: Quickshell.screens', 'model: Quickshell.screens.filter(s => !Quickshell.env("RICE_TEST_OUTPUT") || s.name === Quickshell.env("RICE_TEST_OUTPUT"))')
        path.write_text(text)
    replace('services/HyprlandBackend.qml', 'hl.dsp.focus({workspace = "r${direction === "next" ? "+1" : "-1"}"})', 'workspace r${direction === "next" ? "+1" : "-1"}')
    replace('modules/common/functions/Session.qml', 'Quickshell.execDetached(["loginctl", "lock-session"]);', 'Quickshell.execDetached(["hyprlock"]);')
    replace('modules/common/widgets/WidgetCard.qml', 'radius: Appearance.rounding?.verylarge ?? 30', 'radius: 20')
    replace('modules/common/widgets/WidgetCard.qml', 'color: glass && Config.options.background.widgets.glass.enable ? "transparent" : Appearance.colors.colPrimaryContainer', 'color: glass && Config.options.background.widgets.glass.enable ? "transparent" : Appearance.colors.colLayer1\n    border.width: 1\n    border.color: Qt.rgba(1, 1, 1, 0.1)')
    replace('services/SystemInfo.qml', 'distroIcon = "fedora-symbolic"', 'distroIcon = "arch-symbolic"')
    system_info = destination / 'services/SystemInfo.qml'
    text = system_info.read_text()
    text = re.sub(r'command: \["bash", "-c", "pacman_count=.*?\]\n', 'command: ["python3", Quickshell.shellPath("integration/host.py"), "count"]\n', text)
    system_info.write_text(text)
    updates = destination / 'services/Updates.qml'
    text = updates.read_text().replace('["which", "checkupdates"]', '["python3", Quickshell.shellPath("integration/host.py"), "available"]')
    text = re.sub(r'command: \["bash", "-c", "pacman=.*?\]\n', 'command: ["python3", Quickshell.shellPath("integration/host.py"), "check"]\n', text)
    updates.write_text(text)
    replace('modules/ii/background/widgets/weather/WeatherWidget.qml', 'if (root.sizeMode === "1x1") return oneByOneContent', 'if (!Weather.city && !Weather.gpsActive) return setupPrompt\n                if (root.sizeMode === "1x1") return oneByOneContent')
    replace('modules/ii/background/widgets/weather/WeatherWidget.qml', '        // 1x1', '''        Component {
            id: setupPrompt
            ColumnLayout {
                anchors.fill: parent
                anchors.margins: 18
                StyledText { text: "Set your weather city"; font.pixelSize: 18 }
                StyledText { text: "Choose a city in Services → Weather." }
                Button { text: "Weather settings"; onClicked: GlobalStates.openSettingsAt("services", "Weather", "Weather", "") }
            }
        }
        // 1x1''')
    replace('modules/ii/background/widgets/weather/WeatherWidget.qml', 'import QtQuick.Layouts', 'import QtQuick.Layouts\nimport QtQuick.Controls')
    shutil.copytree(ROOT / 'integration/overrides', destination, dirs_exist_ok=True)
    shutil.copytree(ROOT / 'integration', destination / 'integration', ignore=shutil.ignore_patterns('__pycache__', 'overrides'))
    shutil.copy2(ROOT / 'quickshell/rice-desktop/tasks.py', destination / 'integration/tasks.py')
    # Session screen lock actions must invoke the retained lock implementation too.
    for path in destination.rglob('*.qml'):
        if path.is_symlink():
            continue
        text = path.read_text().replace('GlobalStates.screenLocked = true', 'Quickshell.execDetached(["hyprlock"])')
        path.write_text(text)
    shell = destination / 'shell.qml'
    text = shell.read_text().replace('    ReloadPopup {}', '    ReloadPopup {}\n    RiceBridge {}')
    shell.write_text(text)
    print(destination)
    return destination


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path)
    build(parser.parse_args().destination)
